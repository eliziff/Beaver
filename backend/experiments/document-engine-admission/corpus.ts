/** Export the existing corpus and score physical engine outputs. No engine SDK or model calls. */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { FIXTURES, fixtureBytes } from "../../../benchmarks/docx_edit/src/fixtures";
import { loadTasks } from "../../../benchmarks/docx_edit/src/tasks";
import { scoreTask } from "../../../benchmarks/docx_edit/src/checks";
import type { Task } from "../../../benchmarks/docx_edit/src/types";
import { extractDocxBodyText } from "../../scripts/docx-edit-bench-bridge";

const root = path.resolve(__dirname, "../../.."), here = __dirname;
const sha = (value: string | Buffer) => createHash("sha256").update(value).digest("hex");
const json = async (file: string) => JSON.parse(await readFile(file, "utf8"));
const write = (file: string, value: unknown) => writeFile(file,
  JSON.stringify(value, null, 2) + "\n", { flag: "wx", mode: 0o600 });
const checker = path.join(root, "benchmarks/docx_edit/src/checks.ts");
const readerFiles = ["backend/package-lock.json", "backend/src/lib/docxTrackedChanges.ts",
  "backend/src/lib/docx/session.ts", "backend/src/lib/docx/core.ts", "backend/src/lib/zip.ts"];
const fingerprint = async (files: string[]) => sha(JSON.stringify(await Promise.all(
  files.map(async file => [file, sha(await readFile(path.join(root, file)))]))));
const readerFingerprint = () => fingerprint(readerFiles);
const evaluatorFingerprint = () => fingerprint([
  "backend/experiments/document-engine-admission/corpus.ts",
  "backend/experiments/document-engine-admission/audit.py",
]);
const record = (value: unknown): value is Record<string, any> =>
  value !== null && typeof value === "object" && !Array.isArray(value);

type Fixture = { id: string; file: string; sha256: string };
type Case = { id: string; fixtures: string[]; task?: Task };
type Bundle = { schema: 1; sourceRevision: string; checkerSha256: string; readerSha256: string; evaluatorSha256: string;
  fixtures: Fixture[]; cases: Case[] };

async function safeFile(directory: string, name: unknown) {
  if (typeof name !== "string" || !name || name.includes("\\") ||
      name.split("/").some(part => !part || part === "." || part === "..") || path.isAbsolute(name))
    throw new Error("Invalid artifact path");
  const [base, file] = await Promise.all([realpath(directory), realpath(path.join(directory, name))]);
  const relative = path.relative(base, file);
  if (relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative))
    throw new Error("Artifact escapes its directory");
  return file;
}

async function exportCorpus(destination: string) {
  // Golden files freeze the actual generated bytes; future regeneration is a new bundle.
  const sourceRevision = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  if (execFileSync("git", ["-C", root, "status", "--porcelain", "--untracked-files=no"],
    { encoding: "utf8" }).trim()) throw new Error("Export from a clean tracked checkout");
  const tasks = loadTasks(), fixtures: Fixture[] = [];
  await mkdir(destination, { mode: 0o700 }); // Deliberately refuses existing destinations.
  await mkdir(path.join(destination, "fixtures"), { mode: 0o700 });
  for (const spec of FIXTURES) {
    const bytes = await fixtureBytes(spec.id), file = `fixtures/${spec.id}.docx`;
    await writeFile(path.join(destination, file), bytes, { flag: "wx", mode: 0o600 });
    fixtures.push({ id: spec.id, file, sha256: sha(bytes) });
  }
  const cases: Case[] = [
    ...fixtures.map(({ id }) => ({ id: `roundtrip-${id}`, fixtures: [id] })),
    ...tasks.map(task => ({ id: task.id, fixtures: task.fixtures, task })),
  ];
  const bundle: Bundle = { schema: 1, sourceRevision, checkerSha256: sha(await readFile(checker)), readerSha256: await readerFingerprint(), evaluatorSha256: await evaluatorFingerprint(), fixtures, cases };
  await write(path.join(destination, "bundle.json"), bundle);
  const bundleSha256 = sha(await readFile(path.join(destination, "bundle.json")));
  await write(path.join(destination, "results.template.json"), { schema: 1, bundleSha256,
    engine: { name: "", version: "", distributionSha256: "", runtime: "" },
    cases: cases.map(item => ({ id: item.id, status: "not_run", documents: {} })) });
  console.log(JSON.stringify({ fixtures: fixtures.length, cases: cases.length, bundleSha256 }));
}

function packageAudit(before: string, after: string, bodyMayChange: boolean) {
  let stdout: string;
  const command = process.env.PYTHON_BINARY || (process.platform === "win32" ? "python" : "python3");
  try {
    stdout = execFileSync(command, [path.join(here, "audit.py"), before, after,
      ...(bodyMayChange ? ["--allow-xml", "word/document.xml"] : [])],
    { encoding: "utf8", timeout: 30_000, maxBuffer: 2 * 1024 * 1024 });
  } catch (error) {
    const failure = error as { status?: number; stdout?: string };
    if (![1, 2].includes(failure.status ?? -1) || !failure.stdout) throw error;
    stdout = String(failure.stdout);
  }
  const result = JSON.parse(stdout);
  if (!["passed", "failed", "review_required"].includes(result.status))
    throw new Error("Invalid package audit result");
  return result;
}

async function scoreCorpus(directory: string, resultsFile: string, reportFile: string) {
  const raw = await readFile(path.join(directory, "bundle.json"));
  const bundle = JSON.parse(raw.toString("utf8")) as Bundle;
  if (bundle.schema !== 1 || !Array.isArray(bundle.fixtures) || !bundle.fixtures.length ||
      !Array.isArray(bundle.cases) || !bundle.cases.length ||
      bundle.checkerSha256 !== sha(await readFile(checker)) || bundle.readerSha256 !== await readerFingerprint() ||
      bundle.evaluatorSha256 !== await evaluatorFingerprint()) throw new Error("Invalid or stale corpus/checker");
  const results = await json(resultsFile), engine = results.engine;
  if (results.schema !== 1 || results.bundleSha256 !== sha(raw) || !Array.isArray(results.cases) ||
      !record(engine) || typeof engine.name !== "string" || !engine.name.trim() ||
      typeof engine.runtime !== "string" || !engine.runtime.trim() ||
      !/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(engine.version ?? "") ||
      !/^[a-f0-9]{64}$/.test(engine.distributionSha256 ?? "")) throw new Error("Unbound results or unpinned engine identity");
  const expected = new Map(bundle.cases.map(item => [item.id, item]));
  const fixtureById = new Map(bundle.fixtures.map(item => [item.id, item]));
  if (expected.size !== bundle.cases.length || fixtureById.size !== bundle.fixtures.length)
    throw new Error("Duplicate corpus identity");
  const supplied = new Map<string, Record<string, any>>();
  for (const item of results.cases) {
    if (!record(item) || !expected.has(item.id) || supplied.has(item.id))
      throw new Error("Unknown or duplicate result identity");
    supplied.set(item.id, item);
  }
  const paths = new Map<string, string>(), originalText = new Map<string, string>();
  for (const item of bundle.fixtures) {
    const file = await safeFile(directory, item.file), bytes = await readFile(file);
    if (sha(bytes) !== item.sha256) throw new Error(`Changed fixture: ${item.id}`);
    paths.set(item.id, file);
    originalText.set(item.id, await extractDocxBodyText(bytes));
  }
  const reports = [];
  for (const item of bundle.cases) {
    const result = supplied.get(item.id);
    const successStatus = item.task?.expected === "refuse" ? "refused" : "completed";
    if (!result || result.status !== successStatus) {
      reports.push({ id: item.id, status: "not_passed", reason: result?.status ?? "missing" });
      continue;
    }
    try {
      if (!record(result.documents) || Object.keys(result.documents).length !== item.fixtures.length ||
          Object.keys(result.documents).some(id => !item.fixtures.includes(id)))
        throw new Error("Every in-scope document, including guards, must be supplied");
      const texts = new Map<string, string>(), reopenedTexts = new Map<string, string>();
      const packages = [];
      const changed = new Set((item.task?.reference_edits ?? []).map(edit => edit.fixture ?? item.task!.target_fixture));
      for (const id of item.fixtures) {
        const before = paths.get(id), value = result.documents[id];
        if (!before || !record(value)) throw new Error(`Missing fixture/artifact: ${id}`);
        const output = await safeFile(path.dirname(resultsFile), value.file);
        const reopened = await safeFile(path.dirname(resultsFile), value.reopened);
        if (output === reopened) throw new Error("Export and reopened evidence must be separate files");
        // Audit is a real package read; no model-provided text or pass flag is scored.
        const first = packageAudit(before, output, changed.has(id));
        const second = packageAudit(output, reopened, false);
        const [bytes, reopenedBytes] = await Promise.all([readFile(output), readFile(reopened)]);
        if (first.beforeSha256 !== fixtureById.get(id)?.sha256 || sha(bytes) !== first.afterSha256 || sha(bytes) !== second.beforeSha256 ||
            sha(reopenedBytes) !== second.afterSha256) throw new Error("Artifact changed while scoring");
        texts.set(id, await extractDocxBodyText(bytes));
        reopenedTexts.set(id, await extractDocxBodyText(reopenedBytes));
        packages.push({ fixture: id, exported: first, reopened: second });
      }
      const originals = new Map(item.fixtures.map(id => [id, originalText.get(id)!]));
      const score = (values: Map<string, string>) => item.task
        ? scoreTask({ task: item.task, originals, results: values, answer: typeof result.answer === "string" ? result.answer : "" })
        : { pass: item.fixtures.every(id => values.get(id) === originals.get(id)) };
      const exported = score(texts), reopened = score(reopenedTexts);
      const audits = packages.flatMap(value => [value.exported, value.reopened]);
      const status = !exported.pass || !reopened.pass || audits.some(audit => audit.status === "failed")
        ? "failed" : audits.some(audit => audit.status === "review_required") ? "review_required" : "passed";
      reports.push({ id: item.id, status, exported, reopened, packages });
    } catch (error) {
      reports.push({ id: item.id, status: "failed", reason: String(error) });
    }
  }
  await write(reportFile, { schema: 1, bundleSha256: sha(raw), evaluatorSha256: bundle.evaluatorSha256, engine,
    qualification: "not_admitted", // This corpus alone cannot certify the separate release gates.
    admission: await json(path.join(here, "admission.json")), cases: reports });
  process.exitCode = reports.every(item => item.status === "passed") ? 0 : 1;
}

async function main() {
  const [command, ...args] = process.argv.slice(2);
  if (command === "export" && args.length === 1) return exportCorpus(path.resolve(args[0]));
  if (command === "score" && args.length === 3) return scoreCorpus(...args.map(value => path.resolve(value)) as [string, string, string]);
  throw new Error("Usage: corpus.ts export <new-directory> | score <bundle-directory> <results.json> <new-report.json>");
}
main().catch(error => { console.error(String(error)); process.exitCode = 1; });
